import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import {
  ArrayMaxSize,
  IsArray,
  IsIn,
  IsInt,
  IsString,
  Length,
  Matches,
  MaxLength,
  ValidateNested,
} from 'class-validator';
import { SUPPORTED_LOCALES } from '../../common/locales.js';

export class OtpRequestDto {
  @ApiProperty({
    example: '+915500000002',
    description: 'Indian mobile number; spaces and 0/91 prefixes accepted',
  })
  @IsString()
  @MaxLength(20)
  phone!: string;

  @ApiProperty({ enum: SUPPORTED_LOCALES, description: 'Language of the SMS' })
  @IsIn(SUPPORTED_LOCALES)
  locale!: string;
}

export class OtpRequestResultDto {
  @ApiProperty() expiresInSeconds!: number;
  @ApiProperty() resendAfterSeconds!: number;
}

export class DeviceDto {
  @ApiProperty({ description: 'Installation ID generated by the app', minLength: 8, maxLength: 64 })
  @IsString()
  @Length(8, 64)
  clientId!: string;

  @ApiProperty({ enum: ['android', 'ios', 'web'] })
  @IsIn(['android', 'ios', 'web'])
  platform!: string;

  @ApiProperty({ example: '0.1.0' })
  @Matches(/^\d+\.\d+\.\d+$/)
  appVersion!: string;
}

export class OtpVerifyDto {
  @ApiProperty({ example: '+915500000002' })
  @IsString()
  @MaxLength(20)
  phone!: string;

  @ApiProperty({ example: '123456' })
  @Matches(/^\d{6}$/)
  code!: string;

  @ApiProperty({ type: DeviceDto })
  @ValidateNested()
  @Type(() => DeviceDto)
  device!: DeviceDto;
}

export class ConsentInputDto {
  @ApiProperty({ description: 'Version of the notice the learner saw' })
  @IsInt()
  noticeVersion!: number;

  @ApiProperty({ type: [String], example: ['learning', 'progress_sharing'] })
  @IsArray()
  @ArrayMaxSize(10)
  @IsString({ each: true })
  purposes!: string[];
}

export class RegisterDto {
  @ApiProperty()
  @IsString()
  @Length(20, 100)
  registrationToken!: string;

  @ApiProperty({
    enum: SUPPORTED_LOCALES,
    description: 'Interface language chosen by the learner (FR-102)',
  })
  @IsIn(SUPPORTED_LOCALES)
  locale!: string;

  @ApiProperty({ type: ConsentInputDto })
  @ValidateNested()
  @Type(() => ConsentInputDto)
  consent!: ConsentInputDto;

  @ApiProperty({ type: DeviceDto })
  @ValidateNested()
  @Type(() => DeviceDto)
  device!: DeviceDto;
}

export class RefreshDto {
  @ApiProperty()
  @IsString()
  @Length(20, 100)
  refreshToken!: string;
}

export class TokensDto {
  @ApiProperty() accessToken!: string;
  @ApiProperty() refreshToken!: string;
  @ApiProperty() expiresInSeconds!: number;
  @ApiProperty({ enum: ['Bearer'] }) tokenType!: 'Bearer';
}

export class OnboardingStateDto {
  @ApiProperty({ description: 'Name, district and trade captured (FR-103, step 2b)' })
  profileComplete!: boolean;
}

export class UserSummaryDto {
  @ApiProperty() id!: string;
  @ApiProperty({
    enum: ['learner', 'trainer', 'tomcom_admin', 'author', 'reviewer', 'super_admin'],
  })
  role!: string;
  @ApiProperty({ enum: SUPPORTED_LOCALES }) uiLocale!: string;
  @ApiProperty({ type: OnboardingStateDto }) onboarding!: OnboardingStateDto;
}

export class SessionDto {
  @ApiProperty({ type: TokensDto }) tokens!: TokensDto;
  @ApiProperty({ type: UserSummaryDto }) user!: UserSummaryDto;
}

export class OtpVerifyResultDto {
  @ApiProperty({ enum: ['authenticated', 'registration_required'] })
  status!: 'authenticated' | 'registration_required';

  @ApiPropertyOptional({ type: TokensDto, description: 'When status is authenticated' })
  tokens?: TokensDto;

  @ApiPropertyOptional({ type: UserSummaryDto, description: 'When status is authenticated' })
  user?: UserSummaryDto;

  @ApiPropertyOptional({
    description: 'When status is registration_required: pass to POST /auth/register',
  })
  registrationToken?: string;

  @ApiPropertyOptional()
  registrationExpiresInSeconds?: number;
}
